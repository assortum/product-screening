def load_catalog_rows():
    rows = json.loads((DATA/'catalog'/'part-01.json').read_text(encoding='utf-8'))
    d = json.loads((DATA/'catalog-dict.json').read_text(encoding='utf-8'))
    cats = d['c']
    out=[]
    for pid, cat_idx, name in rows:
        if START_ID <= int(pid) <= END_ID and cats[cat_idx][0] == FURNITURE_MAIN_INDEX:
            out.append({'id': int(pid), 'name': name, 'category': cats[cat_idx][1]})
    if len(out) != 227:
        raise SystemExit(f'Furniture catalog mismatch: expected 227, got {len(out)}')
    return out

def finished_code(name):
    n=name.lower()
    if any(w in n for w in MATTRESS_WORDS): return '940421… / 940429…'
    if any(w in n for w in SEAT_WORDS): return '9401…'
    if any(w in n for w in BED_WORDS): return '940320… / 940350… / 940389…'
    return '9403…'

def make_variant(profile, code, when, result, confidence='средний'):
    return {'profile':profile,'code':code,'when':when,'result':result,'confidence':confidence}

def classify(item):
    name=item['name']; cat=item['category']
    influences=['конструкция и основная функция','материал','самостоятельное готовое изделие или комплектующая','бытовое/общественное/детское/медицинское назначение']
    if name in ELECTRIC_NAMES:
        return {'result':'red','reason':'Активное электрическое изделие требует отдельной оценки электробезопасности/ЭМС.','variants':[make_variant('electric','8543… / иной код группы 85','Активная электрическая вибронакидка/устройство','red')], 'influences':influences}
    if name in MEDICAL_NAMES:
        variants=[make_variant('medical','9402… / 9404… / иной код по конструкции','При подтвержденном медицинском назначении','yellow')]
        if name=='Аксессуары для медицинской мебели':
            variants.append(make_variant('simple-part','8302420000 / 940290… / код по функции','Если это обычная отдельная фурнитура/деталь','green','низкий'))
        else:
            variants.append(make_variant('adult-furniture',finished_code(name),'Если фактически это обычная немедицинская мебель соответствующего вида','red','низкий'))
        return {'result':'yellow','reason':'ТР ТС 025/2012 исключает медицинскую мебель; требуется отделить медицинское изделие от обычной мебели.','variants':variants,'influences':influences}
    if name in CHILD_NAMES:
        return {'result':'red','reason':'Детская/учебная мебель требует обязательной сертификации по ТР ТС 025/2012.','variants':[make_variant('child-furniture',finished_code(name),'Готовая детская, учебная или дошкольная мебель','red','высокий')],'influences':influences}
    if name in SIMPLE_OTHER:
        code='6601100000' if 'зонт' in name.lower() and 'держатель' not in name.lower() else '732690… / 3926909709'
        return {'result':'green','reason':'Простое самостоятельное изделие, не являющееся мебелью; существенная обязательная оценка в базовой проверке не выявлена.','variants':[make_variant('simple-other',code,'Обычное неэлектрическое исполнение','green','средний')],'influences':['материал','конструкция','наличие электрических функций']}
    if name in STRUCTURE_NAMES:
        return {'result':'yellow','reason':'Название может означать мебельный аксессуар либо отдельную строительную/текстильную конструкцию.','variants':[make_variant('structure','6306…','Текстильный тент/шатер/навес','yellow','средний'),make_variant('structure','7308… / 7610…','Металлическая или алюминиевая сборная конструкция','yellow','средний')],'influences':['материал каркаса и покрытия','конструкция','стационарное или переносное исполнение']}
    if name in TEXTILE_NAMES:
        variants=[make_variant('textile','6306… / 6307… / 9404…','Самостоятельное текстильное изделие/принадлежность','yellow','низкий')]
        if 'матрас' in name.lower() or 'топпер' in name.lower():
            variants.append(make_variant('adult-furniture','940421… / 940429…','Если изделие классифицируется как матрас мебельный','red','средний'))
        return {'result':'yellow','reason':'Текстильная принадлежность может регулироваться не как готовая мебель; точный режим зависит от вида изделия.','variants':variants,'influences':['конструкция','наполнитель','наружный материал','самостоятельный матрас или текстильная принадлежность']}
    if name=='Проект кухни под заказ':
        return {'result':'yellow','reason':'Название может означать услугу проектирования либо поставку готовой мебели.','variants':[make_variant('simple-other','ТН ВЭД не применяется','Только услуга проектирования без поставки товара','green','средний'),make_variant('adult-furniture','940340… / 9403…','Поставка кухонной мебели/гарнитура','red','высокий')],'influences':['что именно продается: услуга или мебель','материал и состав комплекта']}
    if name in BUSINESS_AMBIG:
        return {'result':'yellow','reason':'Промышленное/торговое изделие может быть мебелью общественного назначения либо технологическим оборудованием.','variants':[make_variant('adult-furniture','9403…','Если это мебель для общественного/производственного помещения','red','средний'),make_variant('simple-other','7326… / 8419… / иной код по функции','Если это самостоятельное технологическое оборудование/конструкция','yellow','низкий')],'influences':['основная функция','наличие технологических узлов','материал','стационарное или мебельное исполнение']}
    if name in SIMPLE_PART_CODES:
        return {'result':'green','reason':'Типовая отдельная мебельная фурнитура/механическая деталь; не является готовой мебелью.','variants':[make_variant('simple-part',SIMPLE_PART_CODES[name],'Отдельная фурнитура или механическая деталь','green','средний')],'influences':['материал','точная функция и конструкция','поставляется отдельно или в составе готовой мебели']}
    if name in SUBSTANTIAL_PART_NAMES or cat=='Мебельная фурнитура и комплектующие':
        return {'result':'yellow','reason':'Нужно отделить самостоятельную мебельную деталь/фурнитуру от готового мебельного изделия или крупной части группы 94.','variants':[make_variant('simple-part','8302420000 / 940391… / 940399… / код по материалу','Отдельная часть или фурнитура','green','низкий'),make_variant('adult-furniture','9403…','Если фактически продается самостоятельное готовое мебельное изделие','red','низкий')],'influences':influences}
    code=finished_code(name)
    return {'result':'red','reason':'Готовая бытовая/общественная мебель подпадает под обязательное подтверждение соответствия по ТР ТС 025/2012.','variants':[make_variant('adult-furniture',code,'Готовое мебельное изделие','red','высокий')],'influences':influences}

def main():
    products=[]
    for item in load_catalog_rows():
        c=classify(item)
        products.append({
            'id': item['id'], 'name': item['name'], 'subcategory': item['category'],
            'result': c['result'], 'screeningReason': c['reason'], 'influences': c['influences'], 'variants': c['variants']
        })
    batch={'schemaVersion':2,'batchId':'furniture-01','checkedAt':'2026-08-27','mainCategory':'Мебель','sources':SOURCES,'profiles':PROFILES,'products':products}
    counts={'green':0,'yellow':0,'red':0}
    for p in products:
        results={v['result'] for v in p['variants']}
        result='green' if results=={'green'} else 'red' if results=={'red'} else 'yellow'
        counts[result]+=1
    with tempfile.NamedTemporaryFile('w',encoding='utf-8',suffix='.json',delete=False,dir='/tmp') as f:
        json.dump(batch,f,ensure_ascii=False,separators=(',',':'))
        temp_path=f.name
    try:
        subprocess.run([sys.executable,str(ROOT/'scripts'/'build_batch_v2.py'),temp_path],check=True,cwd=ROOT)
    finally:
        Path(temp_path).unlink(missing_ok=True)
    print(f'Furniture merged {len(products)} products: {counts}')

if __name__=='__main__':
    main()
